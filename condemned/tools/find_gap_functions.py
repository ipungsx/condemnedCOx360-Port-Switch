#!/usr/bin/env python3
"""Find the functions ReXGlue's analysis left in gaps between functions, and list them for the manifest.

The analysis finds functions from .pdata, calls and branches. Leaf functions with no .pdata entry that are only
reached through a pointer (vtable thunks, single-blr stubs, C++ static initializers run from the constructor table,
SEH funclets) stay in gaps between detected functions, and the game dies at run time with
"Call to invalid or unregistered function at guest address ...". Run 1 on hardware died that way at 0x83104D58.

    find_gap_functions.py <generated/default> <.text section dump> <text base hex> > recomp/condemned_leaf_functions.toml

The .text dump comes from the codegen tool run with REX_DUMP_SECTIONS=<dir> (tools/rexglue-dump-sections.patch,
applied by tools/codegen.sh).
Each gap is split after every terminal instruction (blr, bctr, b); gaps holding SEH scope tables (pointers to
__C_specific_handler's thunk), switch tables and blocks that do not decode as plausible code are skipped.
After a codegen run with the list, pieces that branch into each other are merged and pieces that branch into the
middle of another function are dropped (see the header of recomp/condemned_leaf_functions.toml).
"""
import collections, glob, os, re, struct, sys

gen, text_path, base = sys.argv[1], sys.argv[2], int(sys.argv[3], 16)
HANDLER_LO, HANDLER_HI = 0x82170000, 0x82174000  # .xidata import thunks (__C_specific_handler lives there)

sizes, ins = {}, re.compile(r"^\t// [a-z]")
for fn in glob.glob(os.path.join(gen, "*_recomp.*.cpp")):
    cur, n = None, 0
    for line in open(fn, errors="replace"):
        if line.startswith("DEFINE_REX_FUNC("):
            cur, n = re.match(r"DEFINE_REX_FUNC\((\w+)\)", line).group(1), 0
            continue
        if cur and ins.match(line):
            n += 1
        if cur and line.startswith("}"):
            sizes[cur], cur = n, None
reg = {}
for fn in glob.glob(os.path.join(gen, "*_register.cpp")):
    for line in open(fn):
        m = re.search(r"SetFunction\(0x([0-9A-F]+), (\w+)\)", line)
        if m:
            reg[int(m.group(1), 16)] = m.group(2)

text = open(text_path, "rb").read() + b"\0" * 4
end_text = (base + len(text) - 4) & ~3
starts = sorted(a for a in reg if base <= a < end_text)
W = lambda a: struct.unpack_from(">I", text, a - base)[0]


def terminal(w):
    return w in (0x4E800020, 0x4E800420) or ((w >> 26) == 18 and not (w & 1))


def plausible(w):
    return w != 0 and (w >> 26) not in (0, 1, 5, 6, 22, 56, 57, 60, 61)


new, skipped = [], collections.Counter()
for i, a in enumerate(starts):
    n = sizes.get(reg[a])
    if n is None:
        continue
    end, nxt = a + 4 * n, starts[i + 1] if i + 1 < len(starts) else end_text
    if nxt <= end:
        continue
    words = [W(o) for o in range(end, nxt, 4)]
    if not any(words):
        continue
    if any(HANDLER_LO <= w < HANDLER_HI for w in words):
        skipped["seh-table"] += 1
        continue
    # A switch table: code addresses right after the function's bctr. The table and the case code after it belong
    # to the function before the gap (its size, counted in instructions, leaves them out).
    if sum(base <= w < end_text for w in words) >= 2:
        skipped["switch-table"] += 1
        continue
    o = end
    while o < nxt:
        while o < nxt and W(o) == 0:
            o += 4
        if o >= nxt:
            break
        s = o
        while o < nxt and W(o) != 0 and not terminal(W(o)):
            o += 4
        if o < nxt and W(o) != 0:
            o += 4
        body = [W(x) for x in range(s, o, 4)]
        if body and all(plausible(w) for w in body) and terminal(body[-1]):
            new.append((s, o - s))
        else:
            skipped["not-code"] += 1
            while o < nxt and W(o) != 0:
                o += 4

print("# Leaf functions and thunks with no .pdata entry that the analysis left in gaps between functions")
print("# (vtable thunks, single-blr stubs, static initializers, SEH funclets). Generated by")
print("# tools/find_gap_functions.py from the codegen output and the XEX .text section.")
print("[functions]")
for s, l in new:
    print(f"0x{s:08X} = {{ size = 0x{l:X} }}")
print(f"{len(new)} functions; skipped {dict(skipped)}", file=sys.stderr)
